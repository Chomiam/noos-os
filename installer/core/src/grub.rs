/// Bootloader identifier passed to `grub-install --bootloader-id`.
pub const BOOTLOADER_ID: &str = "noos-os";

/// The binary the firmware's NVRAM boot entry points at, relative to the ESP root.
///
/// Points at `shimx64.efi` rather than `grubx64.efi` directly: under Secure
/// Boot the firmware only accepts Microsoft-signed binaries, and `shimx64.efi`
/// then chains into `grubx64.efi` (our MOK-signed GRUB core image in the same
/// directory). With Secure Boot disabled `shimx64.efi` still chains
/// transparently, so one NVRAM entry covers both states.
///
/// Backslashes because `efibootmgr` wants the EFI firmware's own path syntax,
/// not a POSIX one.
pub const EFI_LOADER_PATH: &str = "\\EFI\\noos-os\\shimx64.efi";

/// The ESP mount point inside the installed system.
pub const ESP_PATH: &str = "/boot";

/// Filesystem and GPT partition label of the ESP (`mkfs.fat -n` and `sgdisk -c`).
pub const ESP_VOLUME: &str = "NOOS-ESP";

/// Directory where GRUB keeps `grub.cfg`, `grub-btrfs.cfg`, `grubenv` and `themes/`.
pub const GRUB_DIR: &str = "/boot/grub";

/// Main GRUB configuration file generated by `grub-mkconfig`.
pub const GRUB_CFG_PATH: &str = "/boot/grub/grub.cfg";

/// System-wide GRUB defaults file consumed by `grub-mkconfig` and `grub-btrfs`.
