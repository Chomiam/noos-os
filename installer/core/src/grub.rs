/// Kernel parameters written to `GRUB_CMDLINE_LINUX_DEFAULT` in `/etc/default/grub`.
///
/// Does **not** include `root=UUID=...` or `rootflags=subvol=@`: `/etc/grub.d/10_linux`
/// adds those for the normal boot entry, and `/etc/grub.d/41_snapshots-btrfs`
/// adds the snapshot's own `rootflags=...,subvol=@/.snapshots/<N>/snapshot` for
/// snapshot entries.
pub fn kernel_cmdline_default(swap_uuid: Option<&str>) -> String {
    let mut parts = Vec::new();

    if let Some(swap) = swap_uuid {
        parts.push(format!("resume=UUID={swap}"));
    }

    parts.push("quiet".to_string());
    parts.push("splash".to_string());
    parts.push("loglevel=3".to_string());

    parts.join(" ")
}

/// Complete kernel command line for a normal boot of the `@` root subvolume
/// (used for `noos-install check` previews and tests).
pub fn kernel_cmdline(btrfs_uuid: &str, swap_uuid: Option<&str>) -> String {
    format!(
        "root=UUID={btrfs_uuid} rw rootflags=subvol={} {}",
        crate::btrfs::ROOT_SUBVOLUME,
        kernel_cmdline_default(swap_uuid)
    )
}

/// Renders `/etc/default/grub` for the installed system.
pub fn default_grub(swap_uuid: Option<&str>) -> String {
    format!(
        "# Generated by the noos-os installer.\n\
         #\n\
         # Consumed by `grub-mkconfig -o /boot/grub/grub.cfg` and by `grub-btrfs`\n\
         # (`/etc/grub.d/41_snapshots-btrfs`).\n\
         \n\
         GRUB_DEFAULT=0\n\
         GRUB_TIMEOUT=5\n\
         GRUB_DISTRIBUTOR=\"{os_name}\"\n\
         GRUB_CMDLINE_LINUX_DEFAULT=\"{cmdline}\"\n\
         GRUB_CMDLINE_LINUX=\"\"\n\
         \n\
         # Preload partition table and filesystem modules.\n\
         GRUB_PRELOAD_MODULES=\"{preload}\"\n\
         \n\
         GRUB_TIMEOUT_STYLE=menu\n\
         GRUB_TERMINAL_INPUT=console\n\
         GRUB_GFXMODE={gfxmode}\n\
         GRUB_GFXPAYLOAD_LINUX=keep\n\
         GRUB_DISABLE_RECOVERY=true\n\
         \n\
         # WhiteSur GRUB2 theme (https://github.com/vinceliuice/grub2-themes).\n\
         GRUB_THEME=\"{theme}\"\n\
         \n\
         # Keep dual-boot detection active via os-prober.\n\
         GRUB_DISABLE_OS_PROBER=false\n\
         GRUB_DISABLE_BOOTNEXT=true\n\
         GRUB_BTRFS_OVERRIDE_BOOT_PARTITION_DETECTION=true\n",
        os_name = InstallConfig::OS_ENTRY_NAME,
        cmdline = kernel_cmdline_default(swap_uuid),
        preload = GRUB_PRELOAD_MODULES,
        gfxmode = GRUB_GFXMODE,
        theme = THEME_TXT_PATH,
    )
}

/// Arguments passed to `grub-install` inside the target chroot.
pub fn grub_install_args() -> Vec<String> {
    let modules = GRUB_EFI_MODULES.join(" ");
    vec![
        "--target=x86_64-efi".to_string(),
        format!("--efi-directory={ESP_PATH}"),
        format!("--boot-directory={ESP_PATH}"),
        format!("--bootloader-id={BOOTLOADER_ID}"),
        format!("--modules={modules}"),
        format!("--sbat={SBAT_CSV_PATH}"),
        "--disable-shim-lock".to_string(),
        "--no-nvram".to_string(),
        "--recheck".to_string(),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    const BTRFS: &str = "11111111-2222-3333-4444-555555555555";
    const SWAP: &str = "99999999-8888-7777-6666-555555555555";

    #[test]
    fn distributor_is_named_noos_os() {
        let conf = default_grub(None);
        assert!(conf.contains(&format!(
            "GRUB_DISTRIBUTOR=\"{}\"",
            InstallConfig::OS_ENTRY_NAME
        )));
        assert!(conf.contains("GRUB_DISTRIBUTOR=\"noos-os\""));
    }

    #[test]
    fn default_grub_enables_whitesur_theme() {
        let conf = default_grub(None);
        assert!(conf.contains(&format!("GRUB_THEME=\"{THEME_TXT_PATH}\"")));
        assert!(conf.contains("GRUB_THEME=\"/boot/grub/themes/whitesur/theme.txt\""));
        assert!(conf.contains("GRUB_GFXMODE=1920x1080,auto"));
        assert!(conf.contains("GRUB_GFXPAYLOAD_LINUX=keep"));
        assert!(conf.contains("GRUB_TIMEOUT_STYLE=menu"));
    }

    #[test]
    fn default_grub_does_not_force_console_output() {
        // Setting GRUB_TERMINAL_OUTPUT=console disables gfxterm and prevents
        // the WhiteSur theme from rendering at boot.
        let conf = default_grub(None);
        for line in conf.lines() {
            let trimmed = line.trim();
            if !trimmed.starts_with('#') {
                assert!(
                    !trimmed.starts_with("GRUB_TERMINAL_OUTPUT=console"),
                    "GRUB_TERMINAL_OUTPUT=console désactiverait le thème WhiteSur : {line}"
                );
            }
        }
    }

    #[test]
    fn cmdline_default_omits_subvol_so_grub_btrfs_snapshots_work() {
        // `/etc/grub.d/10_linux` adds `rootflags=subvol=@` for the main entry,
        // and `/etc/grub.d/41_snapshots-btrfs` adds `subvol=@/.snapshots/N/snapshot`
        // while also appending `GRUB_CMDLINE_LINUX_DEFAULT`. Having `subvol=@`
        // in `GRUB_CMDLINE_LINUX_DEFAULT` would break snapshot booting.
        let cmdline = kernel_cmdline_default(Some(SWAP));
        assert!(!cmdline.contains("subvol="), "{cmdline}");
        assert!(!cmdline.contains("root="), "{cmdline}");
        assert!(cmdline.contains("quiet"));
        assert!(cmdline.contains("splash"));
        assert!(cmdline.contains("loglevel=3"));
    }

    #[test]
    fn resume_appears_only_with_swap() {
        assert!(!kernel_cmdline_default(None).contains("resume="));
        let with_swap = kernel_cmdline_default(Some(SWAP));
        assert!(with_swap.contains(&format!("resume=UUID={SWAP}")));
        assert!(!with_swap.contains("resume_offset"));
    }

    #[test]
    fn full_kernel_cmdline_includes_root_and_subvolume() {
        let cmdline = kernel_cmdline(BTRFS, Some(SWAP));
        assert!(cmdline.contains(&format!("root=UUID={BTRFS}")));
        assert!(cmdline.contains("rootflags=subvol=@"));
        assert!(cmdline.contains(&format!("resume=UUID={SWAP}")));
    }

    #[test]
    fn os_prober_is_enabled_for_dual_boot() {
        let conf = default_grub(None);
        assert!(conf.contains("GRUB_DISABLE_OS_PROBER=false"));
    }

    #[test]
    fn grub_install_embeds_modules_sbat_and_shim_lock_for_secure_boot() {
        let args = grub_install_args();
        assert!(args.contains(&"--target=x86_64-efi".to_string()));
        assert!(args.contains(&"--efi-directory=/boot".to_string()));
        assert!(args.contains(&"--bootloader-id=noos-os".to_string()));
        assert!(args.contains(&format!("--sbat={SBAT_CSV_PATH}")));
        assert!(args.contains(&"--disable-shim-lock".to_string()));

        let modules_arg = args
            .iter()
            .find(|a| a.starts_with("--modules="))
            .expect("--modules doit être présent");
        for required in [
            "btrfs",
            "zstd",
            "fat",
            "part_gpt",
            "gfxmenu",
            "gfxterm",
            "png",
            "jpeg",
            "font",
            "linux",
            "configfile",
            "search_fs_uuid",
            "probe",
            "chain",
        ] {
            assert!(
                modules_arg.contains(required),
                "module GRUB {required} manquant dans {modules_arg}"
            );
        }
    }

    #[test]
    fn efi_loader_path_points_to_shim_in_noos_os_dir() {
        assert_eq!(EFI_LOADER_PATH, "\\EFI\\noos-os\\shimx64.efi");
        assert!(EFI_LOADER_PATH.starts_with('\\'));
    }
}
