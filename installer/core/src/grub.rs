//! Generating the GRUB bootloader configuration for the installed system.
//!
//! The installed system uses GRUB (`x86_64-efi`) paired with `grub-btrfs` and
//! the WhiteSur graphical theme (`https://github.com/vinceliuice/grub2-themes`).
//!
//! Three design choices matter here:
//!
//! 1. **`GRUB_CMDLINE_LINUX_DEFAULT` deliberately omits `root=UUID=...` and
//!    `rootflags=subvol=@`.** `/etc/grub.d/10_linux` probes `/` and injects
//!    `root=UUID=<btrfs_uuid> rw rootflags=subvol=@` automatically for the main
//!    entry, while `/etc/grub.d/41_snapshots-btrfs` injects
//!    `rootflags=...,subvol=@/.snapshots/<N>/snapshot` for each snapshot entry.
//!    Putting `rootflags=subvol=@` into `GRUB_CMDLINE_LINUX_DEFAULT` would
//!    append it to every snapshot entry as well and override the snapshot
//!    subvolume.
//! 2. **All required GRUB modules and the `.sbat` section are embedded into
//!    `grubx64.efi` at `grub-install` time.** Under UEFI Secure Boot (`shimx64`
//!    → `grubx64.efi`), a thin GRUB core image that tries to `insmod` external
//!    `.mod` files from `/boot/grub/x86_64-efi/` is blocked by lockdown policy.
//!    Pre-embedding the filesystem (`btrfs`, `fat`, `zstd`), graphics (`gfxmenu`,
//!    `gfxterm`, `png`, `jpeg`, `font`) and boot (`linux`, `chain`, `search`,
//!    `configfile`, `probe`) modules plus `--sbat` and `--disable-shim-lock`
//!    makes the MOK-signed `grubx64.efi` self-contained under Secure Boot.
//! 3. **The WhiteSur theme is placed on `/boot/grub/themes/whitesur` as well as
//!    `/usr/share/grub/themes/whitesur`.** Keeping `GRUB_THEME` on the `/boot`
//!    filesystem means both the main `grub.cfg` and the `grub-btrfs.cfg`
//!    submenu resolve `($root)/grub/themes/whitesur/theme.txt` on the same
//!    partition without switching `$root` mid-menu.

