//! Wiring snapper, snap-pac and limine-snapper-sync together.
//!
//! The chain is: `snap-pac` creates a pre/post snapshot around every pacman
//! transaction → snapper records it under the `root` config → the
//! `limine-snapper-sync` snapper plugin copies the matching kernel onto
//! `/boot` and appends a bootable entry to `limine.conf`.

use crate::config::InstallConfig;

/// Snapper config name. It must manage the subvolume mounted at `/`.
pub const SNAPPER_CONFIG_NAME: &str = "root";

/// Tells snapper to work without the system bus.
///
/// Mandatory for every invocation from the installer. `snapper` reaches
/// `snapperd` over D-Bus by default, and an `arch-chroot` has no bus — the
/// call fails with `org.freedesktop.DBus.Error.ServiceUnknown`, which names
/// the bus error rather than the cause.
///
/// The manual warns that a running `snapperd` will not learn about changes
/// made this way. That is exactly right here: there is no daemon in the chroot
/// to inform, and the configuration is written for the next boot.
pub const NO_DBUS: &str = "--no-dbus";

/// Kept equal to `MAX_SNAPSHOT_ENTRIES` below.
///
/// If snapper keeps more snapshots than limine exposes entries for, every sync
/// logs a warning about the surplus; if it keeps fewer, boot entries point at
/// snapshots that cleanup already deleted.
pub const SNAPSHOT_LIMIT: u32 = 10;

/// Path of the limine-snapper-sync config.
///
/// Note it is a plain `.conf`, not the `config.json` used by releases before
/// 1.32 — that file no longer exists.
pub const LIMINE_SNAPPER_SYNC_CONF: &str = "/etc/limine-snapper-sync.conf";

/// Path of the shared limine tooling config, owned by limine-mkinitcpio-hook.
pub const DEFAULT_LIMINE_CONF: &str = "/etc/default/limine";

/// Applied with `snapper -c root set-config KEY=VALUE` rather than by editing
/// `/etc/snapper/configs/root` directly — snapper owns that file's format.
pub fn snapper_settings() -> Vec<(&'static str, String)> {
    vec![
        ("TIMELINE_CREATE", "yes".into()),
        ("TIMELINE_CLEANUP", "yes".into()),
        ("TIMELINE_LIMIT_HOURLY", "5".into()),
        ("TIMELINE_LIMIT_DAILY", "7".into()),
        ("TIMELINE_LIMIT_WEEKLY", "0".into()),
        ("TIMELINE_LIMIT_MONTHLY", "0".into()),
        ("TIMELINE_LIMIT_YEARLY", "0".into()),
        ("NUMBER_LIMIT", SNAPSHOT_LIMIT.to_string()),
        ("NUMBER_LIMIT_IMPORTANT", "5".into()),
        ("EMPTY_PRE_POST_CLEANUP", "yes".into()),
    ]
}

/// systemd units to enable once `/boot` is mounted.
pub const UNITS: &[&str] = &[
    "snapper-timeline.timer",
    "snapper-cleanup.timer",
    "limine-snapper-sync.service",
];

/// Runtime dependency of limine-snapper-sync that is only an *optional*
/// dependency in its PKGBUILD. Without it the watcher never sees snapshot
/// changes and the tool silently does nothing.
pub const REQUIRED_EXTRA_PACKAGES: &[&str] = &["inotify-tools"];

/// AUR packages that make up the snapshot chain.
///
/// Named here because they are what the whole design rests on, and listed in
/// [`crate::install`] as taken from Chaotic-AUR. Both build a GraalVM native
/// image, which is why they cannot simply be compiled on the target — see
/// [`crate::chaotic`]. The test in that module keeps the two lists from
/// drifting apart.
pub const SNAPSHOT_CHAIN_PACKAGES: &[&str] = &["limine-mkinitcpio-hook", "limine-snapper-sync"];

/// Renders `/etc/limine-snapper-sync.conf`.
pub fn limine_snapper_sync_conf(resume_uuid: Option<&str>) -> String {
    let mut out = format!(
        "# Generated by the noos-os installer.\n\
         #\n\
         # TARGET_OS_NAME must match the menu entry in /boot/limine.conf exactly:\n\
         # the Snapshots submenu is hung underneath the entry with that name.\n\
         \n\
         TARGET_OS_NAME=\"{os}\"\n\
         ESP_PATH=\"/boot\"\n\
         MAX_SNAPSHOT_ENTRIES={limit}\n\
         LIMIT_USAGE_PERCENT=85\n",
        os = InstallConfig::OS_ENTRY_NAME,
        limit = SNAPSHOT_LIMIT,
    );

    if let Some(uuid) = resume_uuid {
        // Snapshot entries are generated from the main entry, but whether
        // resume= is carried over is not guaranteed — state it explicitly so
        // hibernation works from a restored snapshot too.
        out.push_str(&format!("SNAPSHOT_KERNEL_PARAMETERS+=\" resume=UUID={uuid}\"\n"));
    }

    out
}

/// Renders `/etc/default/limine`, read by limine-mkinitcpio-hook.
pub fn default_limine_conf() -> String {
    format!(
        "# Generated by the noos-os installer.\n\
         #\n\
         # Read by limine-mkinitcpio-hook, which regenerates the kernel entries\n\
         # in /boot/limine.conf whenever a kernel is installed or removed.\n\
         \n\
         ESP_PATH=\"/boot\"\n\
         TARGET_OS_NAME=\"{os}\"\n\
         KERNEL_CMDLINE[default]+=\" quiet loglevel=3\"\n\
         MAX_SNAPSHOT_ENTRIES={limit}\n",
        os = InstallConfig::OS_ENTRY_NAME,
        limit = SNAPSHOT_LIMIT,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    const SWAP: &str = "99999999-8888-7777-6666-555555555555";

    #[test]
    fn os_name_agrees_with_the_limine_entry() {
        let expected = InstallConfig::OS_ENTRY_NAME;
        assert!(limine_snapper_sync_conf(None).contains(&format!("TARGET_OS_NAME=\"{expected}\"")));
        assert!(default_limine_conf().contains(&format!("TARGET_OS_NAME=\"{expected}\"")));
    }

    #[test]
    fn boot_partition_is_the_esp_at_slash_boot() {
        let conf = limine_snapper_sync_conf(None);
        assert!(conf.contains("ESP_PATH=\"/boot\""));
    }

    #[test]
    fn snapshot_limits_stay_consistent() {
        let snapper_limit = snapper_settings()
            .into_iter()
            .find(|(k, _)| *k == "NUMBER_LIMIT")
            .map(|(_, v)| v)
            .expect("NUMBER_LIMIT doit être réglé");
        assert_eq!(snapper_limit, SNAPSHOT_LIMIT.to_string());

        for conf in [limine_snapper_sync_conf(None), default_limine_conf()] {
            assert!(
                conf.contains(&format!("MAX_SNAPSHOT_ENTRIES={SNAPSHOT_LIMIT}")),
                "limite incohérente avec snapper:\n{conf}"
            );
        }
    }

    #[test]
    fn usage_limit_leaves_room_to_restore() {
        // Above ~90% a FAT32 boot partition can no longer hold the files a
        // restore needs, which blocks recovery exactly when it is wanted.
        let conf = limine_snapper_sync_conf(None);
        let percent: u32 = conf
            .lines()
            .find_map(|l| l.strip_prefix("LIMIT_USAGE_PERCENT="))
            .and_then(|v| v.parse().ok())
            .expect("LIMIT_USAGE_PERCENT doit être présent");
        assert!(percent <= 90, "marge de restauration insuffisante");
    }

    #[test]
    fn resume_is_propagated_to_snapshot_entries() {
        let without = limine_snapper_sync_conf(None);
        assert!(!without.contains("SNAPSHOT_KERNEL_PARAMETERS"));

        let with = limine_snapper_sync_conf(Some(SWAP));
        assert!(with.contains(&format!("SNAPSHOT_KERNEL_PARAMETERS+=\" resume=UUID={SWAP}\"")));
    }

    #[test]
    fn snapper_is_always_called_without_dbus() {
        // The installer runs snapper inside `arch-chroot`, which has no D-Bus.
        // Without this flag `snapper -c root create-config /` fails with
        // `org.freedesktop.DBus.Error.ServiceUnknown` — a message that names
        // the bus error and nothing about the cause, three steps before
        // anything else breaks.
        assert_eq!(NO_DBUS, "--no-dbus");
        assert!(NO_DBUS.starts_with("--"));
    }

    #[test]
    fn inotify_tools_is_required() {
        // It is only an optdepend upstream, but without it the watcher is inert.
        assert!(REQUIRED_EXTRA_PACKAGES.contains(&"inotify-tools"));
    }

    #[test]
    fn the_snapshot_chain_is_the_two_packages_that_cannot_be_compiled() {
        // These are the two that build a GraalVM native image, which is why
        // they come from Chaotic-AUR instead of being built on the target.
        // Renaming one of them here without renaming it upstream would leave
        // the installation reporting success with no snapshot menu anywhere.
        assert_eq!(
            SNAPSHOT_CHAIN_PACKAGES,
            &["limine-mkinitcpio-hook", "limine-snapper-sync"]
        );
        assert!(SNAPSHOT_CHAIN_PACKAGES.contains(&"limine-snapper-sync"));
    }

    #[test]
    fn enables_the_watcher_and_the_timers() {
        assert!(UNITS.contains(&"limine-snapper-sync.service"));
        assert!(UNITS.contains(&"snapper-timeline.timer"));
        assert!(UNITS.contains(&"snapper-cleanup.timer"));
    }
}
