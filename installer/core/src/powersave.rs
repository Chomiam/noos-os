//! Network interface power management.
//!
//! Network cards that enter power-saving mode are a well-known source of
//! trouble on Linux: wireless links that drop or stall under load, and wired
//! links that flap because Energy Efficient Ethernet is mis-negotiated with
//! the switch. On a machine being installed this is worse than an annoyance —
//! a link that sleeps in the middle of `pacstrap` aborts the installation.
//!
//! Note on terminology: there is no environment variable that controls this.
//! Power saving is a property of the driver and the link, set through three
//! different mechanisms, and all three are used here because no single one
//! covers both kinds of interface:
//!
//!  * **Wireless** — `NetworkManager`'s `wifi.powersave`, which is the only
//!    mechanism that survives a reconnect. The driver would otherwise turn
//!    power saving back on by itself.
//!  * **Wired** — Energy Efficient Ethernet, set with `ethtool`. NetworkManager
//!    has no setting for it, so it takes a unit of its own.
//!  * **Both** — a udev rule, so an interface that appears after boot (a USB
//!    adapter, a driver reload) is covered too.

/// `NetworkManager` drop-in disabling wireless power saving.
///
/// `wifi.powersave = 2` means *disable*: 0 is "use the default", 1 is
/// "leave the interface alone", 2 is off, 3 is on. The default is 1, which is
/// why this has to be stated.
///
/// This is the important one. A wireless driver re-enables power saving on
/// every association, so a one-shot `iw dev … set power_save off` at boot
/// would be undone the first time the user joins a network. NetworkManager
/// reapplies it on each connection instead.
pub const NETWORKMANAGER_CONF: &str = "\
# Generated by the noos-os installer.
#
# Disables Wi-Fi power saving.
#
# The driver re-enables it on every association, so this has to be handled by
# whatever manages the connection rather than by a one-shot command at boot.
# NetworkManager reapplies the setting each time an interface comes up.
#
# Values: 0 = driver default, 1 = leave alone, 2 = disabled, 3 = enabled.
# The default is 1, so leaving this out changes nothing.

[connection]
wifi.powersave = 2
";

/// Script that turns off Energy Efficient Ethernet on wired interfaces.
///
/// Written to run from udev as well as from a unit, so it takes the interface
/// name as an argument and falls back to sweeping everything when given none.
pub const EEE_SCRIPT: &str = "\
#!/bin/bash
#
# Generated by the noos-os installer.
#
# Turns off Energy Efficient Ethernet on wired interfaces.
#
# EEE lets a link drop into a low-power state between packets. When it is
# mis-negotiated with the switch — which is common, and rarely the machine's
# fault — the symptom is a link that flaps or stalls, sometimes only under
# load. It is a real power saving on a laptop and a real source of bugs on a
# desktop, and the installer takes the reliable option.
#
# NetworkManager has no setting for EEE, which is why this exists.

set -u

# With an argument, handle just that interface; without, sweep them all.
if [ $# -gt 0 ]; then
    interfaces=(\"$@\")
else
    interfaces=()
    for path in /sys/class/net/*; do
        [ -e \"$path\" ] || continue
        interfaces+=(\"${path##*/}\")
    done
fi

for name in \"${interfaces[@]}\"; do
    # Loopback has no link to negotiate.
    [ \"$name\" = lo ] && continue

    # Wireless interfaces negotiate their own power management; EEE is an
    # Ethernet concept and ethtool would just fail here.
    [ -d \"/sys/class/net/$name/wireless\" ] && continue

    # Not every driver implements EEE. A failure here is expected and not
    # worth reporting: the interface simply does not offer it.
    /usr/bin/ethtool --set-eee \"$name\" eee off >/dev/null 2>&1 || true
done

exit 0
";

/// Unit that applies the script at boot.
///
/// `RemainAfterExit` so the unit reads as active afterwards rather than as a
/// finished job — it describes a state the machine is in, not an action that
/// ran once.
pub const EEE_SERVICE: &str = "\
# Generated by the noos-os installer.
#
# Applies the Energy Efficient Ethernet setting at boot.
#
# The udev rule in /etc/udev/rules.d covers interfaces that appear later; this
# covers the ones already present, and runs after NetworkManager has brought
# them up so the link exists when ethtool is called.

[Unit]
Description=Disable Energy Efficient Ethernet on wired interfaces
Documentation=man:ethtool(8)
After=network.target NetworkManager.service
Wants=network.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/bin/noos-eee-off

[Install]
WantedBy=multi-user.target
";

/// udev rule for interfaces that appear after boot.
///
/// Without this, a USB adapter plugged in later — or a driver reloaded by
/// `modprobe` — would come up with EEE on. udev runs the script per interface,
/// which is why it takes the name as an argument.
///
/// `RUN+=` is used rather than `RUN{program}` because the script must not be
/// allowed to fail the event: on most interfaces `ethtool --set-eee` returns
/// an error, and a non-zero exit from a udev `RUN` is logged as a failure.
pub const EEE_UDEV_RULE: &str = "\
# Generated by the noos-os installer.
#
# Turns off Energy Efficient Ethernet for interfaces that appear after boot.
#
# The script always exits 0, so a driver without EEE support does not produce
# a udev failure on every plug event.

ACTION==\"add\", SUBSYSTEM==\"net\", KERNEL!=\"lo\", RUN+=\"/usr/local/bin/noos-eee-off %k\"
";

/// Path of the generated script on the installed system.
pub const EEE_SCRIPT_PATH: &str = "/usr/local/bin/noos-eee-off";
pub const EEE_SERVICE_PATH: &str = "/etc/systemd/system/noos-eee.service";
pub const EEE_UDEV_PATH: &str = "/etc/udev/rules.d/80-noos-eee.rules";
pub const NETWORKMANAGER_PATH: &str = "/etc/NetworkManager/conf.d/10-noos-powersave.conf";

/// Units to enable, and the one to reload.
pub const EEE_UNIT: &str = "noos-eee.service";

/// `ethtool` is required by the script and is not part of `base`.
pub const REQUIRED_PACKAGES: &[&str] = &["ethtool"];

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn networkmanager_disables_wireless_power_saving() {
        // 2 is "disabled". 0 would mean "use the driver default" and 1 "leave
        // the interface alone", neither of which turns anything off.
        assert!(NETWORKMANAGER_CONF.contains("wifi.powersave = 2"));
        assert!(NETWORKMANAGER_CONF.contains("[connection]"));
    }

    #[test]
    fn networkmanager_config_explains_the_values() {
        // Someone reading this file later has to know that 1 is the default
        // and does nothing.
        let conf = NETWORKMANAGER_CONF;
        assert!(conf.contains("0 = driver default"));
        assert!(conf.contains("2 = disabled"));
    }

    #[test]
    fn the_script_is_a_valid_bash_script() {
        // It is executed by the kernel through a shebang, so it must be
        // self-contained and start with one.
        assert!(EEE_SCRIPT.starts_with("#!/bin/bash"));
        assert!(EEE_SCRIPT.contains("set -u"));
        // Always succeeds: udev logs a non-zero exit as a failure, and most
        // interfaces do not support EEE.
        assert!(EEE_SCRIPT.trim_end().ends_with("exit 0"));
    }

    #[test]
    fn the_script_skips_loopback_and_wireless() {
        // Loopback has no link to negotiate; wireless has no EEE.
        assert!(EEE_SCRIPT.contains(r#"[ "$name" = lo ] && continue"#));
        assert!(EEE_SCRIPT.contains("/wireless\""));
    }

    #[test]
    fn the_script_tolerates_unsupported_interfaces() {
        // `ethtool --set-eee` fails on most drivers. That is not an error.
        assert!(EEE_SCRIPT.contains("2>&1 || true"));
    }

    #[test]
    fn the_script_uses_an_absolute_path_to_ethtool() {
        // udev runs with a minimal PATH, and a relative `ethtool` would not
        // be found.
        assert!(EEE_SCRIPT.contains("/usr/bin/ethtool"));
        assert!(!EEE_SCRIPT.contains(" ethtool --set-eee"));
    }

    #[test]
    fn the_service_runs_after_the_network_is_up() {
        // ethtool needs the link to exist.
        assert!(EEE_SERVICE.contains("After=network.target"));
        assert!(EEE_SERVICE.contains("ExecStart=/usr/local/bin/noos-eee-off"));
        assert!(EEE_SERVICE.contains("WantedBy=multi-user.target"));
        // Describes a state, not a one-shot action.
        assert!(EEE_SERVICE.contains("RemainAfterExit=yes"));
    }

    #[test]
    fn the_udev_rule_covers_new_interfaces() {
        let rule = EEE_UDEV_RULE;
        assert!(rule.contains("SUBSYSTEM==\"net\""));
        assert!(rule.contains("ACTION==\"add\""));
        assert!(rule.contains("KERNEL!=\"lo\""));
        // Passes the interface name, and uses the absolute script path.
        assert!(rule.contains("/usr/local/bin/noos-eee-off %k"));
        // A comment line must not be parsed as a rule.
        assert!(rule.lines().filter(|l| !l.starts_with('#') && !l.trim().is_empty()).count() == 1);
    }

    #[test]
    fn the_generated_paths_are_where_the_units_look_for_them() {
        // The service and the udev rule both name the script by path; a
        // mismatch would leave both silently doing nothing.
        assert!(EEE_SERVICE.contains(EEE_SCRIPT_PATH));
        assert!(EEE_UDEV_RULE.contains(EEE_SCRIPT_PATH));
    }

    #[test]
    fn ethtool_is_declared() {
        assert!(REQUIRED_PACKAGES.contains(&"ethtool"));
    }
}
