//! Keeping audio devices awake.
//!
//! WirePlumber suspends a node once it has been idle, and **the default timeout
//! is five seconds**. On a good deal of hardware the device does not come back
//! cleanly — the sink disappears from the mixer, or the first sound after a
//! silence is lost, or there is a click — so the symptom users report is "the
//! sound stopped working", arriving some seconds after anything was last played.
//!
//! The fix is the `session.suspend-timeout-seconds` property, and setting it to
//! **0 disables the timeout entirely**. That is not an inference: it is what
//! WirePlumber's own script does with the value —
//!
//! ```text
//! local timeout = tonumber (node.properties["session.suspend-timeout-seconds"]) or 5
//! if timeout == 0 then
//!   return
//! end
//! ```
//!
//! — read out of `/usr/share/wireplumber/scripts/node/suspend-node.lua`.
//!
//! The property is set through the *monitors' rules*, not through
//! `wireplumber.settings`: those are the sections the ALSA and Bluetooth
//! monitors read, and the package's own examples use them for this exact
//! property. There is no generic `node.rules` — checked, it appears nowhere in
//! the package — so one rule per monitor is what covers a machine's built-in
//! audio and a Bluetooth headset alike.
//!
//! The cost is real and worth stating: a device that is never suspended keeps
//! drawing its idle power. That is the trade, and it buys an audio stack that
//! does not go quiet on its own.

/// Directory WirePlumber reads system-wide fragments from.
///
/// Third in its search order, after the distribution's own files and before
/// the user's — which is exactly where a distribution default belongs. A user
/// who wants the power saving back can override it from their own config.
pub const CONF_DIR: &str = "/etc/wireplumber/wireplumber.conf.d";

/// The fragment.
///
/// Fragments are read in alphanumerical order within a directory and merged:
/// objects key by key, **arrays by concatenation**. So a `monitor.alsa.rules`
/// here adds a rule rather than replacing the section.
pub const CONF_FILE: &str = "50-noos-no-suspend.conf";

/// The property that decides how long a node may stay idle before suspension.
pub const SUSPEND_PROPERTY: &str = "session.suspend-timeout-seconds";

/// The value that disables suspension.
///
/// Not "a very large number": the script compares against zero and returns, so
/// any other value still suspends eventually and the original symptom returns
/// after a longer silence.
pub const NEVER_SUSPEND: u32 = 0;

/// Node name patterns, one per monitor.
///
/// `~` marks a regular expression in WirePlumber's rule matching. The names are
/// the ones the monitors generate: `alsa_output.pci-…`, `alsa_input.usb-…`,
/// `bluez_output.AC_12_…`.
pub const ALSA_NODES: &str = "~alsa_(output|input).*";
pub const BLUETOOTH_NODES: &str = "~bluez_(output|input).*";

/// Renders the fragment.
///
/// One rule per monitor, built from the same three pieces so the two cannot
/// drift apart.
pub fn no_suspend_conf() -> String {
    let rule = |pattern: &str| {
        format!(
            "    {{\n\
             \x20       matches = [ {{ node.name = \"{pattern}\" }} ]\n\
             \x20       actions = {{\n\
             \x20           update-props = {{\n\
             \x20               {property} = {value}\n\
             \x20           }}\n\
             \x20       }}\n\
             \x20   }}\n",
            pattern = pattern,
            property = SUSPEND_PROPERTY,
            value = NEVER_SUSPEND,
        )
    };

    format!(
        "# Generated by the noos-os installer.\n\
         #\n\
         # WirePlumber suspends an idle audio node after five seconds by default,\n\
         # and on a good deal of hardware it does not come back cleanly — which\n\
         # reads as \"the sound stopped working\". Setting the timeout to 0 makes\n\
         # it never suspend: see node/suspend-node.lua, which returns early when\n\
         # the value is zero.\n\
         #\n\
         # The cost is idle power: a device that never suspends keeps drawing it.\n\
         # To take the power back, remove this file or override it from\n\
         # ~/.config/wireplumber/wireplumber.conf.d/.\n\
         \n\
         monitor.alsa.rules = [\n{alsa}]\n\
         \n\
         monitor.bluez.rules = [\n{bluetooth}]\n",
        alsa = rule(ALSA_NODES),
        bluetooth = rule(BLUETOOTH_NODES),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_timeout_is_disabled_not_merely_raised() {
        // The script compares against zero and returns. Any other value still
        // suspends eventually, so the symptom would come back after a longer
        // silence and look like a different bug.
        assert_eq!(NEVER_SUSPEND, 0);
        assert!(no_suspend_conf().contains("session.suspend-timeout-seconds = 0"));
    }

    #[test]
    fn both_monitors_get_a_rule() {
        // There is no generic `node.rules` section — it appears nowhere in the
        // package — so a built-in sound card and a Bluetooth headset need one
        // rule each. Doing only ALSA would leave headsets going quiet.
        let conf = no_suspend_conf();
        assert!(conf.contains("monitor.alsa.rules = ["));
        assert!(conf.contains("monitor.bluez.rules = ["));
        assert_eq!(conf.matches(SUSPEND_PROPERTY).count(), 2);
    }

    #[test]
    fn the_patterns_are_regular_expressions() {
        // Without the `~` prefix WirePlumber compares literally, and a literal
        // `alsa_(output|input).*` matches no node at all — a rule that reads as
        // correct and does nothing.
        for pattern in [ALSA_NODES, BLUETOOTH_NODES] {
            assert!(pattern.starts_with('~'), "motif non-regex : {pattern}");
        }
    }

    #[test]
    fn the_fragment_lands_where_wireplumber_looks() {
        // Third in the search order: after the distribution's files, before the
        // user's. Read from the WirePlumber 0.5 locations documentation.
        assert_eq!(CONF_DIR, "/etc/wireplumber/wireplumber.conf.d");
        assert!(CONF_FILE.ends_with(".conf"));
        // A leading number so it sorts before a user's own fragment, and so the
        // order is deliberate rather than accidental.
        assert!(CONF_FILE.starts_with("50-"));
    }

    #[test]
    fn the_fragment_reads_exactly_like_this() {
        // Pinned in full, so a change to the rendering is a failing test rather
        // than a fragment nobody reads again.
        //
        // A raw string, not `\`-continued lines: a backslash at end-of-line
        // strips the leading whitespace of the next one, so the indentation
        // would silently vanish from the expectation while remaining in the
        // output. That is exactly what the first version of this test caught.
        let expected = r#"# Generated by the noos-os installer.
#
# WirePlumber suspends an idle audio node after five seconds by default,
# and on a good deal of hardware it does not come back cleanly — which
# reads as "the sound stopped working". Setting the timeout to 0 makes
# it never suspend: see node/suspend-node.lua, which returns early when
# the value is zero.
#
# The cost is idle power: a device that never suspends keeps drawing it.
# To take the power back, remove this file or override it from
# ~/.config/wireplumber/wireplumber.conf.d/.

monitor.alsa.rules = [
    {
        matches = [ { node.name = "~alsa_(output|input).*" } ]
        actions = {
            update-props = {
                session.suspend-timeout-seconds = 0
            }
        }
    }
]

monitor.bluez.rules = [
    {
        matches = [ { node.name = "~bluez_(output|input).*" } ]
        actions = {
            update-props = {
                session.suspend-timeout-seconds = 0
            }
        }
    }
]
"#;

        let actual = no_suspend_conf();
        if actual != expected {
            for (n, (a, e)) in actual.lines().zip(expected.lines()).enumerate() {
                if a != e {
                    panic!(
                        "ligne {} diffère :\n  obtenu   : {a:?}\n  attendu  : {e:?}",
                        n + 1
                    );
                }
            }
            panic!(
                "nombre de lignes différent : {} contre {}",
                actual.lines().count(),
                expected.lines().count()
            );
        }
    }

    #[test]
    fn the_braces_balance() {
        // SPA-JSON is forgiving about separators — `=`, `:`, extra commas and
        // `#` comments are all fine — but not about structure: an unbalanced
        // brace makes the parser drop the whole file, and WirePlumber would
        // start with no rule and say nothing.
        let conf = no_suspend_conf();
        for (open, close) in [('{', '}'), ('[', ']')] {
            let opened = conf.matches(open).count();
            let closed = conf.matches(close).count();
            assert_eq!(opened, closed, "déséquilibre {open}{close} dans :\n{conf}");
        }
    }

    #[test]
    fn the_file_says_how_to_take_the_power_back() {
        // The trade is real — an idle device keeps drawing power — and the way
        // out of it has to be in the file itself.
        let conf = no_suspend_conf();
        assert!(conf.contains("~/.config/wireplumber/"));
        assert!(conf.contains("idle power"));
    }
}
