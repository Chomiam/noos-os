//! The btrfs subvolume layout and the `/etc/fstab` that mounts it.
//!
//! Design rule: exactly one subvolume is snapshotted — `@`, mounted at `/`.
//! Everything the user would be upset to lose (home, logs, caches, root's
//! home) lives in its own subvolume so a rollback of `/` leaves it alone.

/// Options every subvolume gets, apart from the discard and SSD hints.
const BASE_FLAGS: &str = "rw,noatime,compress=zstd:3,space_cache=v2";

/// Options for a solid-state device.
///
/// `discard=async` is the TRIM path: it queues discards out of band rather
/// than blocking on each free, which is what makes it usable. Meaningless on a
/// spinning disk, and the kernel ignores it there.
const SSD_FLAGS: &str = "ssd,discard=async";

/// The mount options for a subvolume, given the kind of disk.
///
/// `ssd` is not just a hint: it changes how btrfs allocates — it stops trying
/// to keep data contiguous for a seek-optimised device. Setting it on a
/// spinning disk is a lie the filesystem believes, and it makes the layout
/// worse for the hardware actually present. The kernel auto-detects the device
/// type, so the honest option is to say nothing and let it.
fn flags_for(subvolume: &Subvolume, rotational: bool) -> String {
    // The disk-type flags apply to every subvolume; only `@tmp` differs in the
    // other direction, because copy-on-write on throwaway data only costs
    // fragmentation.
    let disk = if rotational { "" } else { SSD_FLAGS };

    if subvolume.mount == "/var/tmp" {
        return ["rw,noatime,nodatacow,compress=no", disk, "space_cache=v2"]
            .iter()
            .filter(|part| !part.is_empty())
            .copied()
            .collect::<Vec<_>>()
            .join(",");
    }

    if disk.is_empty() {
        BASE_FLAGS.to_string()
    } else {
        format!("{BASE_FLAGS},{disk}")
    }
}

/// A subvolume created at the top level of the btrfs filesystem, then mounted.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Subvolume {
    /// btrfs subvolume name, e.g. `@home`.
    pub name: &'static str,
    /// Where it is mounted in the installed system.
    pub mount: &'static str,
    /// Whether snapper takes snapshots of it. Only `@` does.
    pub snapshotted: bool,
}

impl Subvolume {
    pub fn mount_options(&self, rotational: bool) -> String {
        format!("{},subvol={}", flags_for(self, rotational), self.name)
    }
}

/// The layout, in creation order.
///
/// `@tmp` gets `nodatacow`: it is throwaway data and copy-on-write there only
/// costs fragmentation. Note that `nodatacow` is never applied to `@` — that
/// would silently disable both snapshots and compression.
///
/// `/.snapshots` is deliberately **not** in this list. `snapper -c root
/// create-config /` creates it itself, as a nested subvolume inside `@`;
/// pre-mounting one of ours at that path makes the command fail outright.
pub const SUBVOLUMES: &[Subvolume] = &[
    Subvolume { name: "@",      mount: "/",          snapshotted: true  },
    Subvolume { name: "@home",  mount: "/home",      snapshotted: false },
    Subvolume { name: "@log",   mount: "/var/log",   snapshotted: false },
    Subvolume { name: "@cache", mount: "/var/cache", snapshotted: false },
    Subvolume { name: "@tmp",   mount: "/var/tmp",   snapshotted: false },
    Subvolume { name: "@root",  mount: "/root",      snapshotted: false },
    Subvolume { name: "@srv",   mount: "/srv",       snapshotted: false },
];

/// The one subvolume snapper manages.
pub const ROOT_SUBVOLUME: &str = "@";

/// Mount options for the ESP at `/boot`.
///
/// `fmask=0133,dmask=0077` is the hardening the Arch wiki recommends once an
/// ESP is mounted at `/boot`: files stay world-readable, but only root can list
/// or write the directory, so an unprivileged process cannot drop a replacement
/// bootloader beside limine. The visible cost is that `ls /boot` is refused for
/// a normal user; every tool that writes there — mkinitcpio, limine-snapper-sync,
/// the kernel install hooks — runs as root.
pub const ESP_MOUNT_OPTIONS: &str = "rw,noatime,fmask=0133,dmask=0077";

/// Renders `/etc/fstab` for the installed system.
///
/// UUIDs are looked up after formatting the partitions, and `subvol=` is used
/// by name rather than `subvolid=`: snapper and limine-snapper-sync resolve
/// subvolumes by name, and mixing the two is a classic source of
/// "snapshots not found".
///
/// `rotational` comes from the target disk's `/sys/block/<disk>/rotational`:
/// passing the SSD options to a spinning disk makes the filesystem lay data
/// out for hardware that is not there.
pub fn fstab(btrfs_uuid: &str, esp_uuid: &str, swap_uuid: Option<&str>, rotational: bool) -> String {
    let mut out = String::from(
        "# /etc/fstab: static file system information.\n\
         #\n\
         # Generated by the noos-os installer.\n\
         #\n\
         # <file system>\t<mount point>\t<type>\t<options>\t<dump>\t<pass>\n",
    );

    for subvolume in SUBVOLUMES {
        out.push_str(&entry(
            &format!("UUID={btrfs_uuid}"),
            subvolume.mount,
            "btrfs",
            &subvolume.mount_options(rotational),
            0,
            0,
        ));
    }

    // pass=2: the ESP is checked after the root filesystem.
    out.push_str(&entry(
        &format!("UUID={esp_uuid}"),
        "/boot",
        "vfat",
        ESP_MOUNT_OPTIONS,
        0,
        2,
    ));

    if let Some(uuid) = swap_uuid {
        out.push_str(&entry(
            &format!("UUID={uuid}"),
            "none",
            "swap",
            "defaults",
            0,
            0,
        ));
    }

    out
}

fn entry(spec: &str, mount: &str, fstype: &str, options: &str, dump: u8, pass: u8) -> String {
    format!("{spec:<40} {mount:<15} {fstype:<6} {options:<72} {dump} {pass}\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    const BTRFS: &str = "11111111-2222-3333-4444-555555555555";
    const ESP: &str = "aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee";
    const SWAP: &str = "99999999-8888-7777-6666-555555555555";

    fn line_for<'a>(fstab: &'a str, mount: &str) -> &'a str {
        fstab
            .lines()
            .find(|l| l.split_whitespace().nth(1) == Some(mount))
            .unwrap_or_else(|| panic!("aucune ligne pour {mount} dans:\n{fstab}"))
    }

    #[test]
    fn exactly_one_subvolume_is_snapshotted() {
        let snapshotted: Vec<_> = SUBVOLUMES.iter().filter(|s| s.snapshotted).collect();
        assert_eq!(snapshotted.len(), 1);
        assert_eq!(snapshotted[0].name, ROOT_SUBVOLUME);
        assert_eq!(snapshotted[0].mount, "/");
    }

    #[test]
    fn root_is_never_nodatacow() {
        for rotational in [false, true] {
            let root = SUBVOLUMES.iter().find(|s| s.mount == "/").unwrap();
            assert!(
                !root.mount_options(rotational).contains("nodatacow"),
                "nodatacow sur / désactiverait snapshots et compression"
            );
        }
    }

    #[test]
    fn no_autodefrag_anywhere() {
        // autodefrag fights copy-on-write and shreds snapshot sharing.
        for subvolume in SUBVOLUMES {
            for rotational in [false, true] {
                assert!(
                    !subvolume.mount_options(rotational).contains("autodefrag"),
                    "autodefrag sur {} se bat avec le COW et les snapshots",
                    subvolume.name
                );
            }
        }
    }

    #[test]
    fn ssd_options_are_only_used_on_an_ssd() {
        // `ssd` is not a hint: it changes how btrfs allocates. Setting it on a
        // spinning disk lays data out for hardware that is not there.
        for subvolume in SUBVOLUMES {
            let ssd = subvolume.mount_options(false);
            let hdd = subvolume.mount_options(true);

            assert!(ssd.contains("ssd,"), "{} : SSD sans option ssd", subvolume.name);
            assert!(ssd.contains("discard=async"));
            assert!(!hdd.contains("ssd"), "{} : ssd sur un disque mécanique", subvolume.name);
            assert!(!hdd.contains("discard="), "{} : discard sur un disque mécanique", subvolume.name);
        }
    }

    #[test]
    fn mounts_every_subvolume_by_name() {
        let fstab = fstab(BTRFS, ESP, None, false);
        for subvolume in SUBVOLUMES {
            let line = line_for(&fstab, subvolume.mount);
            assert!(
                line.contains(&format!("subvol={}", subvolume.name)),
                "la ligne {line} devrait monter {} par nom",
                subvolume.name
            );
            assert!(
                !line.contains("subvolid="),
                "subvolid= est fragile : {line}"
            );
        }
    }

    #[test]
    fn snapshots_are_not_a_mount_point() {
        let fstab = fstab(BTRFS, ESP, Some(SWAP), false);
        assert!(
            !fstab.contains("/.snapshots"),
            "snapper crée /.snapshots lui-même ; l'avoir dans fstab casse create-config"
        );
    }

    #[test]
    fn tmp_is_nodatacow() {
        let fstab = fstab(BTRFS, ESP, None, false);
        assert!(line_for(&fstab, "/var/tmp").contains("nodatacow"));
    }

    #[test]
    fn boot_is_vfat_and_checked_second() {
        let fstab = fstab(BTRFS, ESP, None, false);
        let boot = line_for(&fstab, "/boot");
        assert!(boot.contains("vfat"), "{boot}");
        assert!(boot.ends_with("0 2"), "{boot}");
    }

    #[test]
    fn swap_line_appears_only_when_asked() {
        let without = fstab(BTRFS, ESP, None, false);
        assert!(!without.contains("swap"));

        let with = fstab(BTRFS, ESP, Some(SWAP), false);
        let swap = line_for(&with, "none");
        assert!(swap.contains("swap"));
        assert!(swap.contains(SWAP));
    }

    #[test]
    fn every_line_has_six_fields() {
        let fstab = fstab(BTRFS, ESP, Some(SWAP), false);
        for line in fstab.lines().filter(|l| !l.starts_with('#') && !l.trim().is_empty()) {
            assert_eq!(
                line.split_whitespace().count(),
                6,
                "ligne fstab malformée : {line}"
            );
        }
    }
}
