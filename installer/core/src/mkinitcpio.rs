//! `/etc/mkinitcpio.conf` for the installed system.

/// Listed explicitly even though the `filesystems` hook can pull it in: an
/// initramfs without btrfs is an unbootable system, and being explicit costs
/// nothing.
pub const MODULES: &[&str] = &["btrfs"];

/// Hooks that run before any filesystem is mounted.
const HOOKS_HEAD: &[&str] = &[
    "base",
    "udev",
    "plymouth",
    "autodetect",
    "microcode",
    "modconf",
    "kms",
    "keyboard",
    "keymap",
    "consolefont",
    "block",
];

/// Hooks that mount the real root and overlay read-only btrfs snapshots.
///
/// `grub-btrfs-overlayfs` (shipped by `grub-btrfs`) runs as a late hook at the
/// end of `HOOKS`: when the system boots normally on `@` (`ro=false`), it is a
/// no-op; when the user selects a read-only Snapper snapshot from the
/// `noos-os snapshots` submenu in GRUB (`ro=true`), it mounts a writable tmpfs
/// overlay over `/new_root` so systemd, display managers and services start
/// cleanly without mutating the snapshot.
const HOOKS_TAIL: &[&str] = &["filesystems", "fsck", "grub-btrfs-overlayfs"];

/// The `resume` hook must sit between `block` and `filesystems`: it needs
/// block devices to find the swap partition, and it must run before the root
/// filesystem is mounted for hibernation to work.
pub fn hooks(with_resume: bool) -> Vec<&'static str> {
    let mut hooks = HOOKS_HEAD.to_vec();
    if with_resume {
        hooks.push("resume");
    }
    hooks.extend_from_slice(HOOKS_TAIL);
    hooks
}

pub fn config(with_resume: bool) -> String {
    format!(
        "# Generated by the noos-os installer.\n\
         #\n\
         # `grub-btrfs-overlayfs` sits at the end of HOOKS so that booting a\n\
         # read-only Snapper snapshot from the GRUB menu automatically mounts a\n\
         # writable tmpfs overlay in RAM.\n\
         \n\
         MODULES=({modules})\n\
         BINARIES=()\n\
         FILES=()\n\
         HOOKS=({hooks})\n",
        modules = MODULES.join(" "),
        hooks = hooks(with_resume).join(" "),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hooks_line(with_resume: bool) -> String {
        config(with_resume)
            .lines()
            .find(|l| l.starts_with("HOOKS="))
            .expect("HOOKS doit être présent")
            .to_string()
    }

    #[test]
    fn btrfs_is_in_the_initramfs() {
        assert!(config(false).contains("MODULES=(btrfs)"));
    }

    #[test]
    fn resume_sits_between_block_and_filesystems() {
        let hooks = hooks(true);
        let block = hooks.iter().position(|h| *h == "block").unwrap();
        let resume = hooks.iter().position(|h| *h == "resume").unwrap();
        let filesystems = hooks.iter().position(|h| *h == "filesystems").unwrap();

        assert!(block < resume, "resume a besoin des périphériques bloc");
        assert!(
            resume < filesystems,
            "resume doit tourner avant le montage de la racine"
        );
    }

    #[test]
    fn resume_is_absent_without_swap() {
        assert!(!hooks(false).contains(&"resume"));
        assert!(!hooks_line(false).contains("resume"));
    }

    #[test]
    fn grub_btrfs_overlayfs_is_last_hook() {
        for with_resume in [false, true] {
            let list = hooks(with_resume);
            assert_eq!(
                list.last().copied(),
                Some("grub-btrfs-overlayfs"),
                "grub-btrfs-overlayfs doit être le dernier hook"
            );
            assert!(hooks_line(with_resume).contains("grub-btrfs-overlayfs"));
        }
    }

    #[test]
    fn standard_hooks_are_preserved() {
        let line = hooks_line(false);
        for hook in [
            "base",
            "udev",
            "plymouth",
            "autodetect",
            "microcode",
            "block",
            "filesystems",
            "fsck",
            "grub-btrfs-overlayfs",
        ] {
            assert!(line.contains(hook), "{hook} manquant dans {line}");
        }
    }
}
