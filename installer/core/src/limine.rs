//! Generating `limine.conf` for the installed system.

use crate::config::InstallConfig;
use crate::kernel::Kernel;

/// Kernel image path on the boot partition, for a given kernel.
///
/// `/boot` *is* the ESP, so `boot():/` — the volume holding `limine.conf` —
/// also holds the kernel at its root.
pub fn kernel_path(kernel: Kernel) -> String {
    format!("boot():/{}", kernel.image())
}

pub fn initramfs_path(kernel: Kernel) -> String {
    format!("boot():/{}", kernel.initramfs())
}

/// Kernel command line for a normal boot.
///
/// `resume=` is added whenever a swap partition exists: without it the
/// `resume` hook has nothing to resume from and hibernation silently fails.
/// A swap *partition* needs no `resume_offset=` — that is only required for a
/// swapfile, which is not contiguous.
///
/// `nvidia_drm.modeset=1` is deliberately **not** added. It used to be
/// mandatory for a Wayland session, but `nvidia-utils` has enabled both
/// `modeset` and `fbdev` by default since 560.35.03-5, and the AUR legacy
/// branches patch the same defaults in. Adding it here would be cargo cult.
pub fn kernel_cmdline(btrfs_uuid: &str, swap_uuid: Option<&str>) -> String {
    let mut parts = vec![
        format!("root=UUID={btrfs_uuid}"),
        "rw".to_string(),
        format!("rootflags=subvol={}", crate::btrfs::ROOT_SUBVOLUME),
    ];

    if let Some(swap) = swap_uuid {
        parts.push(format!("resume=UUID={swap}"));
    }

    parts.push("quiet".to_string());
    parts.push("loglevel=3".to_string());

    parts.join(" ")
}

/// Renders the single `limine.conf` that lives at the root of the ESP.
///
/// There must be exactly one: limine stops at the first config it finds in its
/// search path, so a second copy elsewhere would shadow everything
/// `limine-snapper-sync` appends here.
/// Renders the single `limine.conf` that lives at the root of the ESP.
///
/// There must be exactly one: limine stops at the first config it finds in its
/// search path, so a second copy elsewhere would shadow everything
/// `limine-snapper-sync` appends here.
///
/// The entry is named exactly [`InstallConfig::OS_ENTRY_NAME`] and nothing
/// else. Appending the kernel name to it — "/noos-os (linux-zen)" — reads
/// better in the menu but breaks the integration: `limine-snapper-sync`
/// locates the entry to hang its Snapshots submenu under by matching
/// `TARGET_OS_NAME` against the entry name, and a decorated name does not
/// match. The kernel is shown in the installer's summary instead.
pub fn config(btrfs_uuid: &str, swap_uuid: Option<&str>, kernel: Kernel) -> String {
    format!(
        "# Generated by the noos-os installer.\n\
         #\n\
         # This must remain the only limine.conf on the system: limine stops at\n\
         # the first match, and limine-snapper-sync appends its Snapshots submenu\n\
         # to this file.\n\
         #\n\
         # The entry name must stay exactly \"{os_name}\": it is what\n\
         # TARGET_OS_NAME in /etc/limine-snapper-sync.conf matches on.\n\
         #\n\
         # boot():/ is the volume holding this file, i.e. the ESP mounted at /boot.\n\
         \n\
         timeout: 5\n\
         default_entry: 1\n\
         \n\
         /{os_name}\n\
         \x20   protocol: linux\n\
         \x20   path: {kernel}\n\
         \x20   cmdline: {cmdline}\n\
         \x20   module_path: {initramfs}\n",
        os_name = InstallConfig::OS_ENTRY_NAME,
        kernel = kernel_path(kernel),
        cmdline = kernel_cmdline(btrfs_uuid, swap_uuid),
        initramfs = initramfs_path(kernel),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    const BTRFS: &str = "11111111-2222-3333-4444-555555555555";
    const SWAP: &str = "99999999-8888-7777-6666-555555555555";

    #[test]
    fn entry_name_matches_the_snapper_target() {
        let conf = config(BTRFS, None, Kernel::Linux);
        assert!(
            conf.contains(&format!("/{}", InstallConfig::OS_ENTRY_NAME)),
            "limine-snapper-sync cherche TARGET_OS_NAME dans limine.conf:\n{conf}"
        );
    }

    #[test]
    fn entry_name_is_never_decorated() {
        // Appending the kernel name to the entry reads better in the menu but
        // breaks limine-snapper-sync, which matches TARGET_OS_NAME against the
        // entry name exactly.
        let expected = format!("\n/{}\n", InstallConfig::OS_ENTRY_NAME);
        for kernel in Kernel::all() {
            let conf = config(BTRFS, None, kernel);
            assert!(
                conf.contains(&expected),
                "l'entrée doit s'appeler exactement {} pour {:?}:\n{conf}",
                InstallConfig::OS_ENTRY_NAME,
                kernel
            );
        }
    }

    #[test]
    fn kernel_paths_follow_the_chosen_kernel() {
        for (kernel, image, initramfs) in [
            (Kernel::Linux, "boot():/vmlinuz-linux", "boot():/initramfs-linux.img"),
            (Kernel::Lts, "boot():/vmlinuz-linux-lts", "boot():/initramfs-linux-lts.img"),
            (Kernel::Zen, "boot():/vmlinuz-linux-zen", "boot():/initramfs-linux-zen.img"),
        ] {
            let conf = config(BTRFS, None, kernel);
            assert!(conf.contains(&format!("path: {image}")), "{conf}");
            assert!(conf.contains(&format!("module_path: {initramfs}")), "{conf}");
        }
    }

    #[test]
    fn the_wrong_kernel_would_not_boot() {
        // A mismatch between the installed kernel and the path limine boots is
        // the failure this parameterisation exists to prevent: the install
        // succeeds and the machine does not start.
        let lts = config(BTRFS, None, Kernel::Lts);
        assert!(!lts.contains("vmlinuz-linux\n"), "chemin du noyau par défaut dans une config LTS");
        assert!(!lts.contains("initramfs-linux.img"), "initramfs par défaut dans une config LTS");
    }

    #[test]
    fn root_is_mounted_by_uuid_and_subvolume() {
        let conf = config(BTRFS, None, Kernel::Linux);
        assert!(conf.contains(&format!("root=UUID={BTRFS}")));
        assert!(conf.contains("rootflags=subvol=@"));
        assert!(
            !conf.contains("root=/dev/"),
            "un chemin de périphérique casserait le démarrage"
        );
    }

    #[test]
    fn kernel_and_initramfs_are_read_from_the_boot_volume() {
        let conf = config(BTRFS, None, Kernel::Linux);
        assert!(conf.contains("path: boot():/vmlinuz-linux"));
        assert!(conf.contains("module_path: boot():/initramfs-linux.img"));
    }

    #[test]
    fn resume_appears_only_with_swap() {
        assert!(!config(BTRFS, None, Kernel::Linux).contains("resume="));

        let with = config(BTRFS, Some(SWAP), Kernel::Linux);
        assert!(with.contains(&format!("resume=UUID={SWAP}")));
        // A swap partition is contiguous: no offset needed.
        assert!(!with.contains("resume_offset"));
    }

    #[test]
    fn no_nvidia_modeset_parameter() {
        // Deliberate: nvidia-utils has enabled modeset and fbdev by default
        // since 560.35.03-5, and the AUR legacy branches patch the same
        // defaults in, so putting it on the command line would be cargo cult.
        assert!(!config(BTRFS, Some(SWAP), Kernel::Linux).contains("nvidia_drm.modeset"));
    }

    #[test]
    fn one_entry_one_protocol() {
        let conf = config(BTRFS, None, Kernel::Linux);
        assert_eq!(conf.matches("protocol: linux").count(), 1);
        assert_eq!(conf.matches("default_entry:").count(), 1);
    }

    #[test]
    fn indented_keys_are_actually_indented() {
        // limine requires key lines to be indented under the entry; a key at
        // column 0 would be parsed as a new menu entry.
        let conf = config(BTRFS, None, Kernel::Linux);
        for key in ["protocol:", "path:", "cmdline:", "module_path:"] {
            let line = conf
                .lines()
                .find(|l| l.trim_start().starts_with(key))
                .unwrap_or_else(|| panic!("{key} absent"));
            assert!(
                line.starts_with(' ') || line.starts_with('\t'),
                "{key} doit être indenté : {line:?}"
            );
        }
    }
}
