//! Generating the rEFInd configuration for the installed system.
//!
//! rEFInd is a **boot manager**, not a bootloader: it finds EFI binaries and
//! kernels, draws a menu, and hands control over. Where limine needed a
//! hand-written entry per kernel and a hook to rewrite it on every kernel
//! install, rEFInd rescans its volumes on each boot — so the kernel entry here
//! is written once and stays right across upgrades.
//!
//! What rEFInd does *not* do is animate anything. It renders ICNS, PNG, BMP and
//! JPEG — four static bitmap formats, no SVG and no frame sequence. The
//! animated logo lives in Plymouth, which runs from the kernel's first moments
//! to the desktop; this module only produces the static menu.

use crate::config::InstallConfig;
use crate::kernel::Kernel;

/// rEFInd's installation directory on the ESP.
pub const REFIND_DIR: &str = "EFI/refind";

/// The binary the firmware's boot entry points at, relative to the ESP root.
///
/// Backslashes because `efibootmgr` wants the EFI firmware's own path syntax,
/// not a POSIX one.
pub const EFI_LOADER_PATH: &str = "\\EFI\\refind\\refind_x64.efi";

/// The ESP, which is also rEFInd's own volume — so a stanza can name a kernel
/// with a plain path and no `volume` token.
pub const ESP_PATH: &str = "/boot";

/// Where `refind-btrfs` writes the snapshot stanzas.
///
/// Named here so the installer can create it and the tests can pin the path:
/// `refind-btrfs` reads it from its own configuration, and the two have to
/// agree.
pub const SNAPSHOT_DIR: &str = "/EFI/refind/noos-snapshots";

/// Theme directory name, under rEFInd's `themes/`.
pub const THEME_NAME: &str = "noos";

/// Where the live medium keeps the theme's bitmaps.
///
/// Read from the **live system**, not from the target: the theme belongs to the
/// image rather than to any package, so it is not in the target's filesystem
/// until [`crate::install`] copies it onto the ESP.
pub const THEME_SOURCE_DIR: &str = "/usr/share/noos/refind-theme";

/// The bitmaps the theme is made of, generated from `noos-svg.svg` by
/// `scripts/generate-refind-theme.js`.
///
/// Listed explicitly, and asserted against [`theme_conf`] below, so that a file
/// named in the configuration but missing from the image is a test failure
/// rather than a blank menu at boot — where nothing names the missing file.
pub const THEME_FILES: &[&str] = &[
    "background.png",
    "os_noos.png",
    "selection_big.png",
    "selection_small.png",
];

/// Kernel command line for a normal boot.
///
/// **Bootloader-independent** — this is what the kernel itself parses, and it
/// was carried over unchanged from the limine configuration.
///
/// `resume=` is added whenever a swap partition exists: without it the `resume`
/// hook has nothing to resume from and hibernation silently fails. A swap
/// *partition* needs no `resume_offset=` — that is only required for a swapfile,
/// which is not contiguous.
///
/// `nvidia_drm.modeset=1` is deliberately **not** added. It used to be mandatory
/// for a Wayland session, but `nvidia-utils` has enabled both `modeset` and
/// `fbdev` by default since 560.35.03-5, and the AUR legacy branches patch the
/// same defaults in. Adding it here would be cargo cult.
pub fn kernel_cmdline(btrfs_uuid: &str, swap_uuid: Option<&str>) -> String {
    let mut parts = vec![
        format!("root=UUID={btrfs_uuid}"),
        "rw".to_string(),
        format!("rootflags=subvol={}", crate::btrfs::ROOT_SUBVOLUME),
    ];

    if let Some(swap) = swap_uuid {
        parts.push(format!("resume=UUID={swap}"));
    }

    parts.push("quiet".to_string());
    parts.push("loglevel=3".to_string());

    parts.join(" ")
}

/// Renders `/boot/refind_linux.conf`.
///
/// rEFInd reads this beside a kernel it discovered by scanning, to learn the
/// options to boot it with. **The installer writes it, and must**: `refind-install`
/// run inside a chroot fills this file from the *live* system's kernel command
/// line, not the target's — the Arch wiki warns about exactly this, and the
/// result is a kernel panic on first boot, reading as though the install failed.
///
/// The first field is the menu label and the second the options; rEFInd takes
/// the first entry as the default.
pub fn refind_linux_conf(btrfs_uuid: &str, swap_uuid: Option<&str>) -> String {
    format!(
        "# Generated by the noos-os installer.\n\
         #\n\
         # One line per boot option: \"label\"  \"kernel parameters\".\n\
         #\n\
         # Written here rather than left to refind-install, which run from a\n\
         # chroot fills this in from the live medium's own command line — the\n\
         # target would boot with the live kernel's options.\n\
         \n\
         \"noos-os\"\t\"{}\"\n",
        kernel_cmdline(btrfs_uuid, swap_uuid)
    )
}

/// Renders `/boot/EFI/refind/refind.conf`.
///
/// Deliberately short. rEFInd is largely self-configuring: it finds the kernel,
/// finds the theme, and `refind-btrfs` adds its own `include` lines for the
/// snapshot stanzas. Every line here has to earn its place, because a wrong
/// token is ignored in silence.
///
/// There is no `use_nvram false`: rEFInd may maintain its own boot order in
/// NVRAM, and suppressing that is a workaround for Macs, not for this.
///
/// **No `default_selection` pinning the kernel path.** Naming a kernel there
/// means naming its version too, and the entry would go stale on the first
/// kernel upgrade.
pub fn refind_conf(kernel: Kernel) -> String {
    format!(
        "# Generated by the noos-os installer.\n\
         #\n\
         # rEFInd rescans its volumes on every boot, so this file does not have to\n\
         # be rewritten when a kernel is installed or removed. That is why there is\n\
         # no equivalent of limine-mkinitcpio-hook here.\n\
         #\n\
         # The snapshot stanzas are not listed below: refind-btrfs writes them into\n\
         # its own directory and adds its own include lines.\n\
         \n\
         timeout 5\n\
         \n\
         # `internal` and `external` find other EFI loaders; `manual` is what makes\n\
         # the entry below appear at all — without it a menuentry is ignored.\n\
         scanfor internal,external,manual\n\
         \n\
         include themes/{theme}/theme.conf\n\
         \n\
         menuentry \"{os_name}\" {{\n\
         \x20   icon {icon}\n\
         \x20   loader /{kernel}\n\
         \x20   initrd /{initramfs}\n\
         }}\n",
        theme = THEME_NAME,
        os_name = InstallConfig::OS_ENTRY_NAME,
        icon = theme_icon_path(),
        kernel = kernel.image(),
        initramfs = kernel.initramfs(),
    )
}

/// rEFInd's own theme file, `/boot/EFI/refind/themes/noos/theme.conf`.
///
/// Only the banner and the two selection images: the icon for the entry is named
/// in `refind.conf`, and the font is left to rEFInd's own default rather than
/// shipping a `.pf2` this project has no way to generate.
pub fn theme_conf() -> String {
    format!(
        "# Generated by the noos-os installer.\n\
         #\n\
         # rEFInd renders bitmaps, not vectors: everything here is a PNG produced\n\
         # from noos-svg.svg by scripts/generate-refind-theme.js.\n\
         \n\
         banner themes/{theme}/background.png\n\
         banner_scale fillscreen\n\
         \n\
         selection_big themes/{theme}/selection_big.png\n\
         selection_small themes/{theme}/selection_small.png\n\
         \n\
         big_icon_size 128\n\
         small_icon_size 48\n",
        theme = THEME_NAME,
    )
}

/// Path of the icon rEFInd shows beside the `noos-os` entry, as a stanza path.
pub fn theme_icon_path() -> String {
    format!("/EFI/refind/themes/{THEME_NAME}/os_noos.png")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::kernel::Kernel;

    const BTRFS: &str = "11111111-2222-3333-4444-555555555555";
    const SWAP: &str = "99999999-8888-7777-6666-555555555555";

    #[test]
    fn the_entry_is_named_exactly_what_the_distribution_calls_itself() {
        // The name is user-visible and is what any documentation or screenshot
        // refers to. Decorating it with the kernel name was tempting with
        // limine and is tempting here.
        let conf = refind_conf(Kernel::Linux);
        assert!(conf.contains(&format!("menuentry \"{}\"", InstallConfig::OS_ENTRY_NAME)));
        assert!(conf.contains("menuentry \"noos-os\""));
    }

    #[test]
    fn the_entry_loads_the_chosen_kernel() {
        for kernel in Kernel::all() {
            let conf = refind_conf(kernel);
            assert!(
                conf.contains(&format!("loader /{}", kernel.image())),
                "{:?} : le noyau n'est pas celui demandé",
                kernel
            );
            assert!(conf.contains(&format!("initrd /{}", kernel.initramfs())));
        }
    }

    #[test]
    fn a_kernel_is_never_named_with_another_kernels_files() {
        // The path is built from the kernel, and mixing them boots an initramfs
        // that does not match the kernel — a panic that names no cause.
        let conf = refind_conf(Kernel::Lts);
        assert!(!conf.contains("loader /vmlinuz-linux\n"));
        assert!(!conf.contains("initrd /initramfs-linux.img\n"));
    }

    #[test]
    fn manual_scanning_is_enabled() {
        // Without `manual` in `scanfor`, a `menuentry` is silently ignored and
        // the menu shows nothing but whatever rEFInd found by itself.
        assert!(refind_conf(Kernel::Linux).contains("scanfor internal,external,manual"));
    }

    #[test]
    fn the_theme_is_included_and_the_icon_names_a_real_path() {
        let conf = refind_conf(Kernel::Linux);
        assert!(conf.contains(&format!("include themes/{THEME_NAME}/theme.conf")));
        assert!(conf.contains(&theme_icon_path()));
        assert!(theme_icon_path().starts_with("/EFI/refind/themes/"));
    }

    #[test]
    fn root_is_mounted_by_uuid_and_subvolume() {
        let cmdline = kernel_cmdline(BTRFS, None);
        assert!(cmdline.contains(&format!("root=UUID={BTRFS}")));
        assert!(cmdline.contains("rootflags=subvol=@"));
        assert!(!cmdline.contains("root=/dev/"));
    }

    #[test]
    fn resume_appears_only_with_swap() {
        assert!(!kernel_cmdline(BTRFS, None).contains("resume="));
        assert!(kernel_cmdline(BTRFS, Some(SWAP)).contains(&format!("resume=UUID={SWAP}")));
        // Only a swapfile needs this, and the layout deliberately has none.
        assert!(!kernel_cmdline(BTRFS, Some(SWAP)).contains("resume_offset"));
    }

    #[test]
    fn no_nvidia_modeset_parameter() {
        assert!(!kernel_cmdline(BTRFS, None).contains("nvidia_drm.modeset"));
    }

    #[test]
    fn refind_linux_conf_carries_the_same_command_line() {
        // Two places name the kernel options; if they disagree, the entry rEFInd
        // auto-detects boots differently from the one it does not.
        let conf = refind_linux_conf(BTRFS, Some(SWAP));
        assert!(conf.contains(&kernel_cmdline(BTRFS, Some(SWAP))));
        assert!(conf.contains("\"noos-os\""));
    }

    #[test]
    fn refind_linux_conf_labels_and_options_are_tab_separated() {
        // rEFInd splits the line on the first tab; a space is not a separator
        // and the whole line becomes the label.
        let conf = refind_linux_conf(BTRFS, None);
        let line = conf
            .lines()
            .find(|l| l.starts_with("\"noos-os\""))
            .expect("la ligne de démarrage doit exister");
        assert!(line.contains('\t'), "séparateur tabulation attendu : {line}");
    }

    #[test]
    fn nothing_pins_a_kernel_version() {
        // A `default_selection` naming a kernel goes stale on the first kernel
        // upgrade, and the machine boots something that is no longer there.
        let conf = refind_conf(Kernel::Linux);
        assert!(!conf.contains("default_selection"));
    }

    #[test]
    fn the_theme_names_only_files_the_image_ships() {
        // The union of what the two configuration files reference has to be
        // exactly the list the generator produces and the installer copies. A
        // reference to anything else is a blank element at boot, and rEFInd
        // says nothing about it.
        let mut referenced: Vec<String> = Vec::new();
        for conf in [theme_conf(), refind_conf(Kernel::Linux)] {
            for file in THEME_FILES {
                if conf.contains(file) {
                    referenced.push((*file).to_string());
                }
            }
        }
        referenced.sort();
        referenced.dedup();

        let mut expected: Vec<String> = THEME_FILES.iter().map(|f| (*f).to_string()).collect();
        expected.sort();

        assert_eq!(
            referenced, expected,
            "fichiers référencés et fichiers fournis divergent"
        );
    }

    #[test]
    fn the_theme_conf_carries_the_banner_and_the_selections() {
        let conf = theme_conf();
        for file in ["background.png", "selection_big.png", "selection_small.png"] {
            assert!(conf.contains(file), "{file} n'est pas référencé");
        }
        assert!(conf.contains(&format!("themes/{THEME_NAME}/")));
    }

    #[test]
    fn the_icon_and_the_theme_files_agree() {
        // The entry's icon is named in `refind.conf` while the file list lives
        // here; the two drifting apart gives a menu entry with no icon.
        let icon = theme_icon_path();
        let file = icon.rsplit('/').next().expect("un chemin a un dernier segment");
        assert!(
            THEME_FILES.contains(&file),
            "{file} est l'icône de l'entrée mais n'est pas dans THEME_FILES"
        );
    }
}
