//! Optional system services the installer can set up.
//!
//! Each one is a package set plus the units that make it actually work.
//! Enabling the unit is the part that is easy to forget: installing `cups`
//! without enabling `cups.socket` gives a printer stack that is present and
//! inert, and nothing in the UI would say so.

use crate::desktop::Desktop;

/// A feature: what to install, and what to turn on.
pub struct Feature {
    pub packages: &'static [&'static str],
    /// Units to `systemctl enable`. A socket is enabled rather than its
    /// service where one exists, so the daemon starts on first use.
    pub units: &'static [&'static str],
}

/// Bluetooth.
///
/// `bluez` and `bluez-utils` are the stack; the control panel comes from the
/// desktop. GNOME and KDE ship their own (`gnome-bluetooth-3.0`, `bluedevil`),
/// Cinnamon and Budgie do not, so `blueman` covers those — see
/// [`bluetooth_for`].
pub const BLUETOOTH: Feature = Feature {
    packages: &["bluez", "bluez-utils"],
    units: &["bluetooth.service"],
};

/// The GTK Bluetooth manager, for desktops without one of their own.
pub const BLUETOOTH_MANAGER: &str = "blueman";

/// Printing.
///
/// `system-config-printer` is the control panel: CUPS itself has only a web
/// interface on localhost:631, which is not what someone adding a printer
/// expects to be handed.
pub const PRINTING: Feature = Feature {
    packages: &[
        "cups",
        "cups-pk-helper",
        "cups-filters",
        "system-config-printer",
        "gutenprint",
        // Network printer discovery. `nss-mdns` also needs `mdns_minimal` in
        // /etc/nsswitch.conf, which the installer writes.
        "avahi",
        "nss-mdns",
    ],
    units: &["cups.socket", "avahi-daemon.socket"],
};

/// Power profiles.
///
/// `power-profiles-daemon` rather than TLP: it is what GNOME and KDE drive
/// from their own settings panels, so the switch appears where the user will
/// look for it. TLP is more tunable but has no desktop integration and
/// conflicts with the daemon — offering both would let someone install a
/// combination that fights itself.
pub const POWER_PROFILES: Feature = Feature {
    packages: &["power-profiles-daemon"],
    units: &["power-profiles-daemon.service"],
};

/// Bluetooth packages for a given desktop.
///
/// GNOME and KDE bring their own manager; installing `blueman` on top would
/// add a second, redundant control panel.
pub fn bluetooth_for(desktop: Desktop) -> Vec<&'static str> {
    let mut packages = BLUETOOTH.packages.to_vec();
    if matches!(desktop, Desktop::Cinnamon | Desktop::Budgie) {
        packages.push(BLUETOOTH_MANAGER);
    }
    packages
}

/// The `nsswitch.conf` that makes mDNS resolution work.
///
/// `nss-mdns` is useless without `mdns_minimal` in the hosts line, and the
/// default file does not have it. This is the one configuration file the
/// printing feature needs beyond its packages.
pub fn nsswitch_conf() -> &'static str {
    "# Generated by the noos-os installer.\n\
     #\n\
     # mdns_minimal is what nss-mdns hooks into: without it, `.local` names\n\
     # on the network do not resolve and printers are only found by IP.\n\
     # It must come before `resolve` so that mDNS is tried first for `.local`.\n\
     \n\
     passwd: files systemd\n\
     group: files systemd\n\
     shadow: files systemd\n\
     gshadow: files systemd\n\
     \n\
     hosts: mymachines mdns_minimal [NOTFOUND=return] resolve [!UNAVAIL=return] files myhostname dns\n\
     networks: files\n\
     \n\
     protocols: files\n\
     services: files\n\
     ethers: files\n\
     rpc: files\n\
     netgroup: files\n"
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn every_feature_enables_something() {
        // A feature whose packages install but whose units never start is the
        // exact failure this module exists to prevent.
        for (name, feature) in [
            ("bluetooth", &BLUETOOTH),
            ("impression", &PRINTING),
            ("énergie", &POWER_PROFILES),
        ] {
            assert!(
                !feature.units.is_empty(),
                "{name} n'active aucun service"
            );
            assert!(!feature.packages.is_empty(), "{name} n'installe rien");
        }
    }

    #[test]
    fn bluetooth_gets_a_manager_only_where_the_desktop_lacks_one() {
        // GNOME and KDE ship their own; a second panel would be redundant.
        assert!(!bluetooth_for(Desktop::Gnome).contains(&BLUETOOTH_MANAGER));
        assert!(!bluetooth_for(Desktop::Plasma).contains(&BLUETOOTH_MANAGER));
        assert!(bluetooth_for(Desktop::Cinnamon).contains(&BLUETOOTH_MANAGER));
        assert!(bluetooth_for(Desktop::Budgie).contains(&BLUETOOTH_MANAGER));
    }

    #[test]
    fn every_desktop_gets_the_bluetooth_stack() {
        for desktop in Desktop::all() {
            let packages = bluetooth_for(desktop);
            assert!(packages.contains(&"bluez"));
            assert!(packages.contains(&"bluez-utils"));
        }
    }

    #[test]
    fn printing_ships_a_control_panel() {
        // CUPS alone has only a web UI; the feature is not usable without a
        // desktop-side configuration tool.
        assert!(PRINTING.packages.contains(&"system-config-printer"));
        assert!(PRINTING.packages.contains(&"cups"));
    }

    #[test]
    fn printing_enables_the_socket_not_the_service() {
        // Socket activation means the daemon starts on first print instead of
        // idling at every boot.
        assert!(PRINTING.units.contains(&"cups.socket"));
        assert!(!PRINTING.units.contains(&"cups.service"));
    }

    #[test]
    fn power_profiles_does_not_pull_tlp() {
        // The two conflict: PPD is driven by GNOME and KDE settings, TLP by
        // its own config file. Installing both gives an unpredictable machine.
        for package in POWER_PROFILES.packages {
            assert!(
                !package.starts_with("tlp"),
                "tlp entrerait en conflit avec power-profiles-daemon"
            );
        }
        for desktop in Desktop::all() {
            for package in desktop.packages() {
                assert!(!package.starts_with("tlp"));
            }
        }
    }

    #[test]
    fn nsswitch_enables_mdns_before_dns() {
        let conf = nsswitch_conf();
        assert!(conf.contains("mdns_minimal"));

        // mdns_minimal must be tried before the general resolver, otherwise
        // `.local` names go to DNS and fail.
        let hosts = conf
            .lines()
            .find(|line| line.starts_with("hosts:"))
            .expect("la ligne hosts doit exister");
        let mdns = hosts.find("mdns_minimal").expect("mdns_minimal requis");
        let resolve = hosts.find("resolve").expect("resolve requis");
        assert!(mdns < resolve, "mdns_minimal doit précéder resolve");
    }

    #[test]
    fn no_package_appears_twice_within_a_feature() {
        for feature in [&BLUETOOTH, &PRINTING, &POWER_PROFILES] {
            let unique: HashSet<_> = feature.packages.iter().collect();
            assert_eq!(
                unique.len(),
                feature.packages.len(),
                "doublon dans {:?}",
                feature.packages
            );
        }
    }
}
